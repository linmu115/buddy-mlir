"""Check a pipeline stage's public MLIR ABI and emit its C++ binding constants."""

import argparse
import json
import re
from pathlib import Path


def check_signature(directory, phase, inputs, outputs, suffix="-f16"):
    name = f"forward_{phase}"
    source = (directory / f"{name}{suffix}.mlir").read_text()
    matches = re.findall(
        rf"^\s*func\.func @{name}\(([^\n]*)\) -> \(([^\n]*)\)",
        source,
        re.MULTILINE,
    )
    if len(matches) != 1:
        raise ValueError(f"{name} must have exactly one public entry point")
    args, results = matches[0]
    actual = [
        re.findall(r"memref<([^>]+)>", field) for field in (args, results)
    ]
    if actual != [inputs, outputs]:
        raise ValueError(f"{name} ABI differs from stage config: {actual}")
    data_idx = 2 if suffix == "-w4g32" else 1
    print(
        f"{name}: {len(inputs)} inputs, {len(outputs)} results; "
        f"data {inputs[data_idx]} -> {outputs[-1]}"
    )


def verify_w4g32_stage(config, directory, header):
    stage = config["pipeline_stage"]
    start = stage["start_layer"]
    end = stage["end_layer"]
    total = stage["total_layers"]
    count = end - start
    shape = config["shape"]
    width = stage["activation_width"]
    vocab = shape["vocab_size"]
    context = shape["max_token_len"]
    heads = shape["head_num"]
    head_dim = shape["hidden_size"]
    chunk = int(config.get("prefill_chunk", 0))
    weights_by_tag = {w["tag"]: w for w in config["weights"]}
    if (
        not 0 <= start < end <= total
        or stage["activation_type"] != "f32"
        or shape["num_hidden_layers"] != count
        or shape["kv_layers"] != 2 * count
        or chunk <= 0
        or len(config["weights"]) != 2
        or set(weights_by_tag) != {"f32_params", "i8_params"}
        or weights_by_tag["f32_params"]["element_type"] != "f32"
        or weights_by_tag["i8_params"]["element_type"] != "i8"
    ):
        raise ValueError(
            "expected w4g32 stage config with f32 activations, prefill_chunk > 0, "
            "f32_params + i8_params weights, and two KV tensors per layer"
        )

    f32_w = weights_by_tag["f32_params"]
    i8_w = weights_by_tag["i8_params"]
    f32_elems = int(f32_w["num_elements"])
    i8_elems = int(i8_w["num_elements"])
    params = [f"{f32_elems}xf32", f"{i8_elems}xi8"]
    kv = f"1x{heads}x{context}x{head_dim}xf32"
    pos = "1xi64"
    cache = [pos, kv, kv] * count

    for phase, rows in (("prefill", chunk), ("decode", 1)):
        data = f"1x{rows}x{width}xf32" if start else f"1x{rows}xi64"
        out_rows = 1 if (phase == "decode" or end == total) else rows
        output = f"1x{out_rows}x{vocab if end == total else width}xf32"
        inputs = params + [data] + cache
        check_signature(directory, phase, inputs, cache + [output], suffix="-w4g32")

    kernels = directory / "k3_kernels-w4g32.mlir"
    if not kernels.is_file():
        raise ValueError(f"missing w4g32 kernel module: {kernels}")
    if config.get("prefill_ime"):
        ime_kernels = directory / "k3_kernels_ime-w4g32.mlir"
        if not ime_kernels.is_file():
            raise ValueError(f"missing w4g32 IME kernel module: {ime_kernels}")

    for w, bpe in ((f32_w, 4), (i8_w, 1)):
        path = directory / w["file"]
        expected_bytes = int(w["num_elements"]) * bpe
        actual_bytes = path.stat().st_size
        if actual_bytes != expected_bytes:
            raise ValueError(
                f"{path}: weight file length {actual_bytes} differs from "
                f"expected {expected_bytes}"
            )

    print(
        f"layer range [{start}, {end}); {count * 2} KV tensors (f32); "
        f"{f32_elems} f32 params ({f32_elems * 4} B) + "
        f"{i8_elems} q4/i8 bytes"
    )

    if header:
        fields = [
            start,
            end,
            total,
            context,
            width,
            vocab,
            config["tokens"]["eos_id"],
        ]
        signature = ", ".join(["PositionRef *, KVRef *, KVRef *"] * count)
        use_arena = "true" if config.get("arena") else "false"
        use_ime = "true" if config.get("prefill_ime") else "false"
        header.write_text(
            "// Generated by verify_pipeline_stage.py (w4g32).\n"
            "constexpr StageConfig config{"
            + ", ".join(map(str, fields))
            + ", ActivationType::F32};\n"
            f"constexpr int prefillChunk = {chunk};\n"
            f"constexpr bool useArena = {use_arena};\n"
            f"constexpr bool usePrefillIme = {use_ime};\n"
            f"constexpr size_t f32WeightElements = {f32_elems};\n"
            f"constexpr size_t i8WeightElements = {i8_elems};\n"
            f"constexpr size_t kvHeads = {heads};\n"
            f"constexpr size_t headDim = {head_dim};\n"
            f"constexpr char f32WeightFile[] = {json.dumps(f32_w['file'])};\n"
            f"constexpr char i8WeightFile[] = {json.dumps(i8_w['file'])};\n"
            "#define BUDDY_STAGE_DECODE_ARGS " + signature + "\n"
        )


def verify_stage(config, directory, header):
    if config.get("variant") == "w4g32":
        verify_w4g32_stage(config, directory, header)
        return
    stage = config["pipeline_stage"]
    start = stage["start_layer"]
    end = stage["end_layer"]
    total = stage["total_layers"]
    count = end - start
    shape = config["shape"]
    width = stage["activation_width"]
    vocab = shape["vocab_size"]
    context = shape["max_token_len"]
    heads = shape["head_num"]
    head_dim = shape["hidden_size"]
    (weights,) = config["weights"]
    elements = weights["num_elements"]
    if (
        not 0 <= start < end <= total
        or stage["activation_type"] != "f16"
        or weights["element_type"] != "f16"
        or shape["num_hidden_layers"] != count
        or shape["kv_layers"] != 2 * count
    ):
        raise ValueError(
            "expected FP16 stage config with two KV tensors per layer"
        )

    param = f"{elements}xf16"
    kv = f"1x{heads}x{context}x{head_dim}xf16"
    pos = "1xi64"
    for phase, rows in (("prefill", context), ("decode", 1)):
        data = f"1x{rows}x{width}xf16" if start else f"1x{rows}xi64"
        output = f"1x{rows}x{vocab if end == total else width}xf16"
        cache = (
            [kv, kv] * count if phase == "prefill" else [pos, kv, kv] * count
        )
        inputs = [param, data] + (cache if phase == "decode" else [])
        check_signature(directory, phase, inputs, cache + [output])

    path = directory / weights["file"]
    if path.stat().st_size != elements * 2:
        raise ValueError(
            f"{path}: weight file length differs from the stage config"
        )
    print(
        f"layer range [{start}, {end}); {count * 2} KV tensors; {elements} FP16 weights"
    )

    if header:
        fields = [
            start,
            end,
            total,
            context,
            width,
            vocab,
            config["tokens"]["eos_id"],
        ]
        signature = ", ".join(["PositionRef *, KVRef *, KVRef *"] * count)
        header.write_text(
            "// Generated by verify_pipeline_stage.py.\n"
            "constexpr StageConfig config{"
            + ", ".join(map(str, fields))
            + ", ActivationType::F16};\n"
            f"constexpr size_t weightElements = {elements};\n"
            f"constexpr size_t kvHeads = {heads};\n"
            f"constexpr size_t headDim = {head_dim};\n"
            f"constexpr char weightFile[] = {json.dumps(weights['file'])};\n"
            "#define BUDDY_STAGE_DECODE_ARGS " + signature + "\n"
        )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stage-dir", type=Path, required=True)
    parser.add_argument("--header", type=Path)
    args = parser.parse_args()
    config = json.loads((args.stage_dir / "config.json").read_text())
    verify_stage(config, args.stage_dir, args.header)


if __name__ == "__main__":
    main()
